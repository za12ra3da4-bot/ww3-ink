const PI = Math.PI;
const GEO = new Map();
const cache = (key, make) => {
  let g = GEO.get(key);
  if (!g) { g = make(); GEO.set(key, g); }
  return g;
};

// 옆모습 [z, y] 다각형 → 폭 w 로 밀어내고 모서리를 굴린다. holes: 구멍 다각형 목록
const prof = (pts, w, holes = [], bevel = 0.004) => () => cache(`p${JSON.stringify(pts)}${w}${JSON.stringify(holes)}`, () => {
  const shape = new THREE.Shape(pts.map(([z, y]) => new THREE.Vector2(z, y)));
  for (const h of holes) shape.holes.push(new THREE.Path(h.map(([z, y]) => new THREE.Vector2(z, y))));
  const b = Math.min(bevel, w * 0.3);
  const g = new THREE.ExtrudeGeometry(shape, { depth: Math.max(0.001, w - b * 2), bevelEnabled: true, bevelThickness: b, bevelSize: b, bevelSegments: 2, curveSegments: 8 });
  g.translate(0, 0, -(w - b * 2) / 2);
  g.rotateY(-PI / 2);
  g.computeVertexNormals();
  return g;
});
const box = (w, h, d) => () => cache(`b${w},${h},${d}`, () => new THREE.BoxGeometry(w, h, d));
const cylZ = (r1, r2, len, seg = 14, open = false) => () => cache(`cz${r1},${r2},${len},${seg},${open}`, () => new THREE.CylinderGeometry(r1, r2, len, seg, 1, open).rotateX(PI / 2));
const cylX = (r1, r2, len, seg = 10) => () => cache(`cx${r1},${r2},${len},${seg}`, () => new THREE.CylinderGeometry(r1, r2, len, seg).rotateZ(PI / 2));
const cylY = (r1, r2, len, seg = 12) => () => cache(`cy${r1},${r2},${len},${seg}`, () => new THREE.CylinderGeometry(r1, r2, len, seg));
const sphere = (r) => () => cache(`s${r}`, () => new THREE.SphereGeometry(r, 12, 8));
const torus = (r, t, arc = PI * 2) => () => cache(`t${r},${t},${arc}`, () => new THREE.TorusGeometry(r, t, 6, 16, arc));
// 회전체 [반지름, z] → z 축 둘레로 돌린다
const latheZ = (pts, seg = 20) => () => cache(`l${JSON.stringify(pts)}`, () => new THREE.LatheGeometry(pts.map(([r, z]) => new THREE.Vector2(r, z)), seg).rotateX(PI / 2));

const ring = (z0, z1, y0, y1, w, t = 0.006) => prof([[z0, y0], [z1, y0], [z1, y1], [z0, y1]], w, [[[z0 - t, y0 - t], [z1 + t, y0 - t], [z1 + t, y1 + t], [z0 - t, y1 + t]]], 0.002);
const repeat = (n, fn) => Array.from({ length: n }, (_, i) => fn(i));

